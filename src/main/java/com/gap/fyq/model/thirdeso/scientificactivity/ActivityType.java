package com.gap.fyq.model.thirdeso.scientificactivity;

public enum ActivityType {

    /** Cálculo de Error Absoluto (Ea = |Ve − Vt|) y Error Relativo (Er = Ea/Vt × 100 %). */
    ERROR_CALCULATION,

    /** Conversión de magnitudes derivadas complejas: densidad (g/cm³ ↔ kg/m³)
     *  y velocidad (km/h ↔ m/s) con análisis dimensional paso a paso. */
    ADVANCED_CONVERSION,

    /** Preguntas conceptuales sobre tablas de datos: identificar proporcionalidad
     *  directa, inversa, cuadrática o relación no lineal. */
    GRAPH_PROPORTIONALITY
}
